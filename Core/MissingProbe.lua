--Results still accumulate across runs, so a name seen present once is never
--reported missing later.
SLASH_OCTOUIMISSING1 = "/octoui-missing"
SlashCmdList["OCTOUIMISSING"] = function()
	ElvDB = ElvDB or {}
	ElvDB.SeenGlobals = ElvDB.SeenGlobals or {}

	local loaded = 0
	for i = 1, table.getn(LOD_ADDONS) do
		if not IsAddOnLoaded(LOD_ADDONS[i]) then
			LoadAddOn(LOD_ADDONS[i])
		end
		if IsAddOnLoaded(LOD_ADDONS[i]) then loaded = loaded + 1 end
	end
	DEFAULT_CHAT_FRAME:AddMessage(string.format(
		"|cff1784d1OctoUI|r probe: %d of %d load-on-demand addons available.",
		loaded, table.getn(LOD_ADDONS)))

	local seen = ElvDB.SeenGlobals
	local total = table.getn(CANDIDATES)
	local missing, count, newly = {}, 0, 0

	for i = 1, total do
		local name = CANDIDATES[i]
		if getglobal(name) ~= nil then
			if not seen[name] then
				seen[name] = true
				newly = newly + 1
			end
		elseif not seen[name] then
			count = count + 1
			missing[count] = name
		end
	end

	ElvDB.MissingGlobals = missing

	DEFAULT_CHAT_FRAME:AddMessage(string.format(
		"|cff1784d1OctoUI|r probe: %d of %d never seen (%d newly found this run).",
		count, total, newly))

	--Names the compatibility layer overwrote that the client already had. See the
	--comment at the top of !Compatibility/api/luaAPI.lua for why this matters.
	if OctoUI_ClobberedGlobals then
		ElvDB.ClobberedGlobals = OctoUI_ClobberedGlobals
		DEFAULT_CHAT_FRAME:AddMessage(string.format(
			"|cff1784d1OctoUI|r compat layer overwrote %d pre-existing client function(s).",
			table.getn(OctoUI_ClobberedGlobals)))
	end

	DEFAULT_CHAT_FRAME:AddMessage("Now /reload to flush the results to disk.")
end
